package main

// Промт и транскрипт агента КП (2026-11-14, шаг P6).
//
// Промт — серверный, потому что модель зовёт сервис (у бота своей модели нет).
// Он задаёт ровно две вещи, которые не выразить инструментами:
//   1) форму ответа (один JSON-объект — протокол канона);
//   2) правило «инструмент есть граница»: документы без привязки к продукту и
//      письма без PDF не возвращаются ни одним инструментом, поэтому модель
//      объясняет пустой результат, а не ищет обход.
// Всё остальное — в описаниях инструментов: их модель читает из схем.

import (
	"encoding/json"
	"fmt"
	"strings"
)

// agentSystemPrompt — системный промт хода. Схемы инструментов вставляются

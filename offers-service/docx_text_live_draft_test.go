package main

import (
	"strings"
	"testing"
)

// Живой ответ модели начинается с черновика вёрстки, а за ним идёт настоящий
// текст — и раньше в документ не попадало НИ ОДНОГО из двух (2026-11-06).
//
// Ответ КП 003/2026, скачанный из form_values (`gen.layout.46f1df42…`) после
// неудачной генерации: первые строки модель тратит на заголовок вёрстки и
// пересказ задания, дальше идёт готовый текст для заказчика. Прежний
// cleanBlockText видел строку «Заголовок: "…"», считал весь ответ планом и
// возвращал пустую строку: в макете осталось десять пустых абзацев, и
// «куда делась описательная часть» оказалось вопросом без ответа.
//
// Правило: строку-МАРКЕР вёрстки снимаем как маркер, а текст за ней оставляем.
// Черновые строки (план, рассуждение, английская речь) выбрасываются по одной.
func TestCleanBlockTextKeepsTextAfterHeadingMarker(t *testing.T) {
	answer := `1. "Гидроизоляция фундамента: одна система на горизонталь, вертикаль и отмостку".

Заголовок: "Система ТН-ФУНДАМЕНТ Дренаж Проф закрывает весь подземный контур дома"
Текст: задача объекта — новый многоквартирный дом с подземной автостоянкой на Примерной, зимние работы и жёсткие сроки; нужна гидроизоляция фундамента.

Заголовок: "Горизонтальная часть: мембрана 2 мм, швы под контролем"
Состав: Logicbase V-SL 2 мм 5520 м2 + усиление на ДШ 121 м2, геотекстиль ПЭТ 500 г 10560 м2.
Преимущества: сварка горячим воздухом с двойным швом и воздушным каналом — герметичность проверяема; карты до 150 м2 с инъекционными штуцерами — ремонт без вскрытия.`

	out := cleanBlockText(answer)
	if strings.TrimSpace(out) == "" {
		t.Fatal("ответ с настоящим текстом после маркера вёрстки выброшен целиком")
	}
	for _, want := range []string{
		"задача объекта — новый многоквартирный дом",
		"Состав: Logicbase V-SL 2 мм",
		"герметичность проверяема",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("из ответа потерян текст %q:\n%s", want, out)
		}
	}
	for _, unwanted := range []string{"Заголовок:", "Текст:", "1. \"Гидроизоляция фундамента"} {
		if strings.Contains(out, unwanted) {
			t.Errorf("в документ ушёл черновик %q:\n%s", unwanted, out)
		}
	}
}

// Сирота-маркер без содержимого и ссылка на вёрстку — по-прежнему черновик:
// клиенту они не говорят ничего.
func TestCleanBlockTextDropsBareHeadingMarker(t *testing.T) {
	for _, answer := range []string{
		"Заголовок:",
		"Text: ",
		"Ссылки (Heading 1)",
		"Цена",
	} {
		if got := cleanBlockText(answer); got != "" {
			t.Errorf("сирота-маркер не отсечён (%q), осталось:\n%s", answer, got)
		}
	}
}

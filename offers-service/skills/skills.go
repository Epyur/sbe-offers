package skills

// SectionKind — какую секцию документа пишем. Ключ попадает в form_values
// предложения как copy.<kind>.
type SectionKind string

const (
	// SectionIntro — «Предлагаем Вам, для объекта … использовать материалы …».
	SectionIntro SectionKind = "intro"
	// SectionSystem — описание системы: что это и зачем на этом объекте.
	SectionSystem SectionKind = "system"
	// SectionAdvantages — преимущества системы: список, а не абзац.
	SectionAdvantages SectionKind = "advantages"
	// SectionConditions — подводка к условиям поставки (сами условия — из формы).
	SectionConditions SectionKind = "conditions"
)

// AllSections — порядок, в котором бот пишет и согласовывает секции.
func AllSections() []SectionKind {
	return []SectionKind{SectionIntro, SectionSystem, SectionAdvantages, SectionConditions}
}


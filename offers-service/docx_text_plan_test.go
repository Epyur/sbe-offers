// План модели — это оглавление будущего текста, а не текст (2026-11-06).
//
// Живой ответ КП 003/2026 на просьбу описать систему:
// «1. Intro (задача объекта, что предлагаем, цена). 2. h2 "Состав решения" —
// перечень слоёв. 3. h2 "Мембрана LOGICBASE V-SL: …"». В документе это
// выглядело как готовый раздел, но ни одного предложения для заказчика в нём
// не было. Решение пользователя: лучше пустой блок, чем план.
func TestCleanBlockTextDropsPlan(t *testing.T) {
	plan := `1. Intro (задача объекта, что предлагаем, цена).
2. h2 "Состав решения" - перечень слоёв (список).
3. h2 "Мембрана LOGICBASE V-SL: сварной шов, который проверяют воздухом" - описание + преимущества.
4. h2 "Гидрошпонки: швы и деформационные узлы остаются герметичными"`
	if got := cleanBlockText(plan); got != "" {
		t.Fatalf("план не отсечён, в документ ушло:\n%s", got)
	}
}

func TestCleanBlockTextDropsHeadingMarker(t *testing.T) {
	for _, answer := range []string{
		"Heading 2: \"Гидроизоляционный слой: мембрана сваривается в двойной шов\"",
		"Heading \"Геотекстиль и плёнка разделяют слои\"\nText: геотекстиль 500 г/м2",
		"Section: Задача на объекте\n\nSection: Состав решения",
		"Intro: коротко о системе\n\nOutro: вывод",
	} {
		if got := cleanBlockText(answer); got != "" {
			t.Errorf("маркер вёрстки не отсечён (%q), осталось:\n%s", answer, got)
		}
	}
}

// Настоящий нумерованный состав — НЕ план и вырезаться не должен.
//
// Состав конструкции в КП почти всегда список слоёв. Отсекать его как
// «оглавление» значит оставить пустым самый нужный раздел документа.
func TestCleanBlockTextKeepsNumberedComposition(t *testing.T) {
	composition := `Состав системы ТН-ФУНДАМЕНТ Дренаж Проф:
1. Подготовка основания под фундаментную плиту.
2. Уплотнённый грунт и гравийно-песчаная подготовка.
3. ПВХ-мембрана LOGICBASE V-SL 2 мм с двойным сварным швом.
4. Геотекстиль иглопробивной ПЭТ 500 г/м2.
5. Защитно-дренажное полотно PLANTER Geo.
6. Теплоизоляция XPS CARBON PROF 100 мм.`
	out := cleanBlockText(composition)
	if out == "" {
		t.Fatal("настоящий нумерованный состав принят за план и выброшен")
	}
	for _, want := range []string{
		"1. Подготовка основания", "3. ПВХ-мембрана", "6. Теплоизоляция",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("из состава потерян пункт %q:\n%s", want, out)
		}
	}
}

// Маркер вёрстки посреди настоящего текста не выбрасывает текст: состав с
// подписью «Состав системы» остаётся, даже если рядом есть слово часть.
func TestCleanBlockTextKeepsTextNearOrdinaryWords(t *testing.T) {
	text := `Гидроизоляция подземной части выполняется одной системой.
Мембрана сваривается горячим воздухом в двойной шов.
Каждая карта до 150 м2 с инъекционными штуцерами.`
	if got := cleanBlockText(text); strings.TrimSpace(got) == "" {
		t.Fatal("обычный текст принят за план")
	}
}

// Объём, заданный в подсказке, читается (2026-11-06).
func TestRequestedWords(t *testing.T) {
	cases := map[string]int{
		"Объем текста не менее 4000 знаков на одну систему.": 666,
		"Напиши не меньше 500 слов":                          500,
		"4000 символов в абзаце":                             666,
		"Опиши систему в двух абзацах":                       0,
		"": 0,
	}
	for instruction, want := range cases {
		if got := skills.RequestedWords(instruction); got != want {
			t.Errorf("RequestedWords(%q) = %d, ожидалось %d", instruction, got, want)
		}
	}
}

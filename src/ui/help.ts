/**
 * Строки «готовая метка — что печатает» из одного списка меток.
 *
 * Справка не должна расходиться с именем метки: список живёт в `markers.ts`, и
 * серверная сверка проверяет его же. Строка собирается, а не пишется руками —
 * иначе после добавления метки справка молча устареет (так уже было с
 * `{{текст: система: description}}`, 2026-11-07).
 */
function markerLines(): string[] {
  const lines: string[] = [];
  for (const group of MARKER_GROUPS) {
    lines.push(`${group.title}: ` + group.variants.map((v) => `${v.marker} — ${v.label}`).join('; ') + '.');
  }
  return lines;
}


// Проверка, что собранный main.js содержит кириллические строки редактора в
// экранированном виде. esbuild экранирует кириллицу в `\uXXXX` ЗАГЛАВНЫМИ
// (правило проекта 2026-09-22), поэтому искать неэкранированную форму
// бессмысленно — и этот скрипт есть единственный надёжный способ проверки.
import fs from 'node:fs';

const bundle = fs.readFileSync('main.js', 'utf8');

/** Строка в том виде, в каком её пишет esbuild: \uXXXX на каждый символ > 127. */
function escaped(text) {
  return Array.from(text)
    .map((ch) => {
      const code = ch.codePointAt(0);
      if (code <= 127) return ch;
      // hex ВЕРХНИМ регистром: esbuild пишет `\u0420`, и поиск строчными даёт
      // ложное «строки нет» — та же грабля, что была в 2026-09-22.
      return '\\' + 'u' + code.toString(16).toUpperCase().padStart(4, '0');
    })
    .join('');
}

const needles = [
  'Разрыв страницы',
  'Текст по промту',
  'Обтекание',
  'Начните вводить имя картинки',
  'Не разрывать между страницами',
  'С новой страницы',
  // Тела узлов `image` и `links`: без них редактор покажет пустые строки.
  'Картинка справа, текст слева',
  'Картинка плавающая: текст идёт рядом с ней, строка не разрывается.',
  'Ссылки собираются из карточек систем и материалов',
  'Что написать (подсказка для модели):',
  // Справка, которую человек видит: она должна быть про нынешний порядок.
  'Материалы и системы',
  'начинается с разговора о контексте',
  // Текст новости ЦУП выпуска 0.4.2 (правило: переписывается каждый выпуск).
  'Бот научился понимать присланные файлы',
  'можно собрать и без позиций',
];

let missing = 0;
for (const text of needles) {
  const ok = bundle.includes(escaped(text));
  if (!ok) missing++;
  console.log((ok ? 'OK   ' : 'MISS ') + text);
}
console.log(`отсутствует: ${missing}`);
process.exit(missing === 0 ? 0 : 1);
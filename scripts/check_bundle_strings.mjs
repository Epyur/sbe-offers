// Проверка, что собранный main.js содержит кириллические строки редактора в
// экранированном виде. esbuild экранирует кириллицу в `\uXXXX` ЗАГЛАВНЫМИ
// (правило проекта 2026-09-22), поэтому искать неэкранированную форму
// бессмысленно — и этот скрипт есть единственный надёжный способ проверки.
import fs from 'node:fs';

const bundle = fs.readFileSync('main.js', 'utf8');

/** Строка в том виде, в каком её пишет esbuild: \uXXXX на каждый символ > 127. */
function escaped(text) {
  return Array.from(text)
    .map((ch) => {
      const code = ch.codePointAt(0);
      if (code <= 127) return ch;
      // hex ВЕРХНИМ регистром: esbuild пишет `\u0420`, и поиск строчными даёт
      // ложное «строки нет» — та же грабля, что была в 2026-09-22.
      return '\\' + 'u' + code.toString(16).toUpperCase().padStart(4, '0');
    })
    .join('');
}


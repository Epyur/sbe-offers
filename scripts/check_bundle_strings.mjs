  'Материалы и системы',
  'начинается с разговора о контексте',
  // Текст новости ЦУП выпуска 0.4.2 (правило: переписывается каждый выпуск).
  // Строки выпуска 0.4.3: подпись формы и новость ЦУП переписаны. Две строки
  // прошлого выпуска («Код ЕКН» в новости, «В таблице предложения появился
  // столбец») сняты 2026-11-02 вместе с текстом новости 0.4.3.
  'Номер предложения',
  'В форме есть строки, которые клиент прочитает как черновик:',
  // Выпуск 0.4.4: выбор системы в карточке КП и в боте — по заметке, а не по
  // коду, которого у живых карточек нет. Строка новости 0.4.4 снята 2026-11-02
  // вместе с текстом новости; «Выберите систему» остаётся — это проверка отказа.
  'Выберите систему',
  // Выпуск 0.4.5: слои и работы в составе больше не выдаются за ошибку.
  'есть замечания к составу',
  'Слои без материала:',
  // Выпуск 0.5.0: выбор системы больше не добавляет позиции (2026-11-03).
  // Строка новости 0.4.5 снята вместе с текстом новости.
  'Система в КП:',
